// Regenerates src/theme/tailwindPalettes.ts from the installed Tailwind theme, so theme presets
// use Tailwind's exact colours. Run after upgrading Tailwind: node scripts/gen-theme-palettes.mjs
import { readFileSync, writeFileSync } from "node:fs";

const css = readFileSync("node_modules/tailwindcss/theme.css", "utf8");
const { version } = JSON.parse(readFileSync("node_modules/tailwindcss/package.json", "utf8"));
const names = ["teal", "emerald", "cyan", "sky", "blue", "indigo", "violet", "fuchsia", "rose", "pink", "orange", "red", "amber", "green", "slate", "zinc"];
const shades = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];

let out = `// Generated by scripts/gen-theme-palettes.mjs from tailwindcss ${version}. Do not edit by hand.\n`;
out += "// Each shade is [lightness 0-1, chroma, hue] in OKLCH.\n\n";
out += `export const SHADES = [${shades.join(", ")}] as const;\nexport type Shade = (typeof SHADES)[number];\n`;
out += "export type Oklch = readonly [number, number, number];\nexport type Palette = Readonly<Record<Shade, Oklch>>;\n\n";
out += "export const TAILWIND_PALETTES = {\n";
for (const name of names) {
	const entries = shades.map((shade) => {
		const m = css.match(new RegExp(`--color-${name}-${shade}: oklch\\(([\\d.]+)% ([\\d.]+) ([\\d.]+|none)\\)`));
		if (!m) throw new Error(`Missing --color-${name}-${shade} in tailwindcss/theme.css`);
		return `${shade}: [${+(Number(m[1]) / 100).toFixed(4)}, ${m[2]}, ${m[3] === "none" ? 0 : m[3]}]`;
	});
	out += `\t${name}: { ${entries.join(", ")} },\n`;
}
out += "} as const satisfies Record<string, Palette>;\n\nexport type PaletteName = keyof typeof TAILWIND_PALETTES;\n";
writeFileSync("src/theme/tailwindPalettes.ts", out);
console.log(`Wrote ${names.length} palettes`);
